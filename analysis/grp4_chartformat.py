import torch

from transformers import (
    AutoImageProcessor,
    AutoModelForSemanticSegmentation
)

MODEL_NAME = 'nvidia/segformer-b0-finetuned-ade-512-512'

device = torch.device(
    'cuda' if torch.cuda.is_available() else 'cpu'
)

setup_start = time.perf_counter()

processor = AutoImageProcessor.from_pretrained(MODEL_NAME)

model = AutoModelForSemanticSegmentation.from_pretrained(
    MODEL_NAME
)

model = model.to(device).eval()

setup_seconds = time.perf_counter() - setup_start

labels = {
    int(k): value.strip().lower()
    for k, value in model.config.id2label.items()
}

def ids_for(names):
    return {
        key for key, value in labels.items()
        if value in names
    }

TREE_IDS = ids_for({'tree'})
VEGETATION_IDS = ids_for({'tree', 'grass', 'plant'})
SKY_IDS = ids_for({'sky'})
BUILDING_IDS = ids_for({'building'})

assert (
    TREE_IDS and VEGETATION_IDS
    and SKY_IDS and BUILDING_IDS
), 'Required model labels are missing.'

print(f'Model loaded successfully on {device}.')
print(f'Loading time: {setup_seconds:.1f} seconds')

COLOURS = {
    0: (0, 0, 0),
    1: (0, 180, 0),
    2: (0, 120, 255),
    3: (255, 0, 0)
}

palette = np.array(
    [COLOURS[i] for i in range(4)],
    dtype=np.uint8
)

rows = []

inference_start = time.perf_counter()

for number, photo_path in enumerate(photos, start=1):

    image_id = photo_path.stem

    with Image.open(photo_path) as original:
        image = ImageOps.exif_transpose(original).convert('RGB')

    image.thumbnail((1200, 1200))

    image.save(ANALYSIS_DIR / f'{image_id}.png')

    start = time.perf_counter()

    inputs = processor(
        images=image,
        return_tensors='pt'
    ).to(device)

    with torch.no_grad():
        outputs = model(**inputs)

    prediction = processor.post_process_semantic_segmentation(
        outputs,
        target_sizes=[(image.height, image.width)]
    )[0].cpu().numpy()

    model_seconds = time.perf_counter() - start

    simple_mask = np.zeros(
        prediction.shape,
        dtype=np.uint8
    )

    simple_mask[
        np.isin(prediction, list(VEGETATION_IDS))
    ] = 1

    simple_mask[
        np.isin(prediction, list(SKY_IDS))
    ] = 2

    simple_mask[
        np.isin(prediction, list(BUILDING_IDS))
    ] = 3

    Image.fromarray(simple_mask).save(
        AI_MASK_DIR / f'{image_id}.png'
    )

    Image.fromarray(palette[simple_mask]).save(
        COLOUR_DIR / f'{image_id}.png'
    )

    rgb = np.array(image, dtype=np.float32)
    overlay = rgb.copy()

    chosen = simple_mask > 0

    overlay[chosen] = (
        0.60 * rgb[chosen]
        + 0.40 * palette[simple_mask][chosen]
    )

    Image.fromarray(
        overlay.astype(np.uint8)
    ).save(OVERLAY_DIR / f'{image_id}.png')

    rows.append({
        'photo_filename': photo_path.name,
        'playground_id': image_id,
        'vegetation_pct': round(
            100 * np.mean(simple_mask == 1), 2
        ),
        'tree_pct_AI_only': round(
            100 * np.mean(
                np.isin(prediction, list(TREE_IDS))
            ), 2
        ),
        'sky_pct': round(
            100 * np.mean(simple_mask == 2), 2
        ),
        'buildings_pct': round(
            100 * np.mean(simple_mask == 3), 2
        ),
        'ai_processing_seconds': round(model_seconds, 2)
    })

    print(f'[{number}/{len(photos)}] Completed: {image_id}')

processing_seconds = time.perf_counter() - inference_start

results = pd.DataFrame(rows)

results.to_csv(ROOT / 'ai_results.csv', index=False)

