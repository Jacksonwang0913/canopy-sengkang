# Commented out IPython magic to ensure Python compatibility.
# %pip -q install transformers

import io
from pathlib import Path

import numpy as np
import matplotlib.pyplot as plt
import torch
from PIL import Image, ImageOps
from matplotlib.patches import Patch
from matplotlib.colors import to_rgb
from transformers import AutoImageProcessor, AutoModelForSemanticSegmentation
from google.colab import files

MODEL_NAME = 'nvidia/segformer-b0-finetuned-ade-512-512'
device = torch.device('cuda' if torch.cuda.is_available() else 'cpu')

processor = AutoImageProcessor.from_pretrained(MODEL_NAME)
model = AutoModelForSemanticSegmentation.from_pretrained(MODEL_NAME)
model = model.to(device).eval()

class_names = {
    int(class_id): str(name).strip()
    for class_id, name in model.config.id2label.items()
}
print(f'SegFormer is ready! Running on: {device}')

uploaded = files.upload()

if len(uploaded) != 1:
    raise ValueError('Please choose exactly ONE playground photo.')

photo_name = next(iter(uploaded))
if Path(photo_name).suffix.lower() not in {'.jpg', '.jpeg', '.png'}:
    raise ValueError('Please choose a JPG or PNG photograph, not a ZIP.')

with Image.open(io.BytesIO(uploaded[photo_name])) as photo:
    image = ImageOps.exif_transpose(photo).convert('RGB')

# Resize large photos for easier processing, but keep their original proportions.
image.thumbnail((1200, 1200))
print(f'Uploaded: {photo_name} | Size: {image.width} × {image.height} pixels')

# 4A. Ask SegFormer to classify every pixel
inputs = processor(images=image, return_tensors='pt').to(device)

with torch.no_grad():
    outputs = model(**inputs)

prediction = processor.post_process_semantic_segmentation(
    outputs,
    target_sizes=[(image.height, image.width)]
)[0].cpu().numpy()

# 4B. Choose bright, consistent colours for familiar features
chosen_colours = {
    'tree': '#09c52b',
    'sky': '#00ddf4',
    'building': '#f4979d',
    'grass': '#a2ed00',
    'plant': '#178e52',
    'road': '#9a9a9a',
    'sidewalk': '#bcbec0',
    'floor': '#85765a',
    'wall': '#d9a391',
    'earth': '#75512d',
    'person': '#f0b941',
    'car': '#7040df',
    'water': '#3573dc',
    'fence': '#d39a64',
}

# Other possible classes receive different automatic colours.
rainbow = plt.get_cmap('gist_rainbow')
palette = np.array([
    [int(channel * 255) for channel in rainbow((i * 0.618) % 1)[:3]]
    for i in range(model.config.num_labels)
], dtype=np.uint8)

for class_id, name in class_names.items():
    if name.lower() in chosen_colours:
        palette[class_id] = np.array(to_rgb(chosen_colours[name.lower()])) * 255

colour_segmentation = palette[prediction]

# 4C. Create the legend of detected classes, largest area first
detected_ids, pixel_counts = np.unique(prediction, return_counts=True)
detected = sorted(zip(detected_ids, pixel_counts), key=lambda pair: pair[1], reverse=True)

legend = [
    Patch(
        color=palette[class_id] / 255,
        label=f'{class_names[int(class_id)]}: {count / prediction.size * 100:.1f}%'
    )
    for class_id, count in detected
]

# 4D. Show the original ABOVE the segmentation, with legend BELOW
legend_rows = int(np.ceil(len(legend) / 4))
bottom_space = max(0.14, 0.055 * legend_rows)

fig = plt.figure(figsize=(11, 8 + 0.45 * legend_rows), facecolor='white')
grid = fig.add_gridspec(
    2, 1, left=0.04, right=0.96, top=0.95,
    bottom=bottom_space, hspace=0.16
)

top = fig.add_subplot(grid[0])
bottom = fig.add_subplot(grid[1])

top.imshow(image)
top.set_title('1. Original Playground Photograph', fontsize=13)
top.axis('off')

bottom.imshow(colour_segmentation)
bottom.set_title('2. Full AI Semantic Segmentation', fontsize=13)
bottom.axis('off')

fig.legend(
    handles=legend,
    loc='lower center',
    bbox_to_anchor=(0.5, 0.01),
    ncol=4,
    fontsize=9,
    frameon=False
)

# Save exactly the figure that appears in Colab
output_name = f'{Path(photo_name).stem}_SegFormer_Result.png'
plt.savefig(output_name, dpi=180, facecolor='white', bbox_inches='tight')
plt.show()

print('Finished! Output image saved as:', output_name)

