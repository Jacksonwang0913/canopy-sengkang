def analyse_photo_to_record(photo, playground_id, location='', postal_code='',
                            exact_coordinates='', lat=None, lon=None,
                            shelter='Unclear', source='Online source not yet verified',
                            lenient_location=False):
    if photo is None:
        raise gr.Error('Please upload one playground photograph.')
    if not str(playground_id).strip():
        raise gr.Error('Please enter a playground ID, such as P001.')

    try:
        lat, lon, map_source = resolve_playground_location(
            photo, postal_code, exact_coordinates, lat, lon
        )
    except gr.Error as error:
        if not lenient_location:
            raise
        lat, lon = None, None
        map_source = f'Not mapped; location requires review: {error}'

    image, original_size, mask = classify_photo(photo)
    full_figure = make_full_figure(image, mask)
    focused = make_focus_mask(mask)

    share = lambda class_list: round(100 * np.mean(np.isin(mask, class_list)), 2)
    tree = share(TREE_IDS)
    lower = share(LOW_VEG_IDS)
    vegetation = share(VEGETATION_IDS)
    sky = share(SKY_IDS)
    building = share(BUILDING_IDS)

    quality_note = 'Review AI output: playground equipment is not a dedicated class'
    if min(original_size) < 500:
        quality_note += '; small image'
    if source == 'Online source not yet verified':
        quality_note += '; photo rights not verified'
    quality_note += f'; {map_source}'

    location_text = str(location or '').strip()
    postal_text = re.sub(r'^[Ss]\s*', '', str(postal_code or '').strip())
    if postal_text and postal_text not in location_text:
        location_text = f'{location_text} (S{postal_text})'.strip()

    record = dict(
        playground_id=str(playground_id).strip(),
        location=location_text,
        latitude=lat, longitude=lon,
        tree_pct=tree, other_vegetation_pct=lower,
        vegetation_pct=vegetation, sky_pct=sky, buildings_pct=building,
        shelter_visible=shelter, photo_source=source,
        photo_quality_note=quality_note,
        screening_note='Pending comparison'
    )
    return full_figure, focused, record, map_source

def analyse_and_save(photo, playground_id, location, postal_code,
                     exact_coordinates, lat, lon, shelter, source, records):
    full_figure, focused, record, map_source = analyse_photo_to_record(
        photo, playground_id, location, postal_code, exact_coordinates,
        lat, lon, shelter, source
    )
    rows = [dict(x) for x in (records or [])
            if str(x.get('playground_id')) != record['playground_id']]
    rows.append(record)   # Re-analysing an ID updates that record, not a duplicate.
    df = results_table(rows)
    updated_rows = df.to_dict(orient='records')

    coords = (f'{record["latitude"]:.6f}, {record["longitude"]:.6f}'
              if record['latitude'] is not None else 'No mapped point')
    status = (f'### Image results: {html.escape(record["playground_id"])}\n'
              f'- **Tree canopy:** {record["tree_pct"]}% of visible pixels\n'
              f'- **Other vegetation:** {record["other_vegetation_pct"]}%\n'
              f'- **Total vegetation:** {record["vegetation_pct"]}% (includes tree)\n'
              f'- **Visible sky:** {record["sky_pct"]}%\n'
              f'- **Buildings:** {record["buildings_pct"]}%\n'
              f'- **Map point:** {html.escape(map_source)} ({coords})\n'
              f'- **Manual shelter observation:** {shelter}\n\n'
              '**Interpretation:** Photo-level indicators only. This is not a shade or rain-safety rating.\n\n'
              f'**Verification note:** {html.escape(record["photo_quality_note"])}')

    return (full_figure, focused, status,
            df, create_map(df), save_csv(df), updated_rows)

def import_saved_csv(filepath):
    if not filepath:
        raise gr.Error('Choose your previously downloaded results CSV.')
    df = pd.read_csv(filepath)
    missing = set(COLUMNS) - set(df.columns)
    if missing:
        raise gr.Error(f'CSV is missing columns: {sorted(missing)}')
    df = df[COLUMNS].copy().drop_duplicates('playground_id', keep='last')
    for col in ['tree_pct', 'other_vegetation_pct', 'vegetation_pct',
                'sky_pct', 'buildings_pct']:
        df[col] = pd.to_numeric(df[col], errors='coerce')
    if df[['tree_pct', 'sky_pct']].isna().any().any():
        raise gr.Error('CSV contains invalid percentages.')
    df = results_table(df.to_dict(orient='records'))
    return (df, create_map(df), save_csv(df), df.to_dict(orient='records'),
            f'Loaded {len(df)} saved playground records. You can continue analysing.')

