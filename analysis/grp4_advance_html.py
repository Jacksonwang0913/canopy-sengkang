def get_onemap_token():
    global ONEMAP_TOKEN, ONEMAP_EXPIRY
    if not ONEMAP_EMAIL or not ONEMAP_PASSWORD:
        raise gr.Error('Postal-code lookup needs a OneMap account. '
                       'Enter credentials when running Step 3, '
                       'or enter both coordinates manually.')
    if ONEMAP_TOKEN and time.time() < ONEMAP_EXPIRY - 300:
        return ONEMAP_TOKEN
    try:
        response = requests.post(
            'https://www.onemap.gov.sg/api/auth/post/getToken',
            json={'email': ONEMAP_EMAIL, 'password': ONEMAP_PASSWORD},
            timeout=20
        )
        response.raise_for_status()
        login = response.json()
    except (requests.RequestException, ValueError):
        raise gr.Error('OneMap login is unavailable. Try again later '
                       'or enter coordinates manually.')
    token = login.get('access_token')
    if not token:
        raise gr.Error('OneMap login failed. Check your registered '
                       'email and password.')
    ONEMAP_TOKEN = token
    ONEMAP_EXPIRY = float(login.get('expiry_timestamp', time.time() + 3600))
    return ONEMAP_TOKEN

def postal_to_coordinates(postal_code):
    global ONEMAP_TOKEN, ONEMAP_EXPIRY
    match = re.fullmatch(r'[Ss]?\s*(\d{6})', str(postal_code or '').strip())
    if not match:
        raise gr.Error('Enter a six-digit Singapore postal code, e.g. 200640.')
    postcode = match.group(1)

    for attempt in range(2):
        token = get_onemap_token()
        try:
            response = requests.get(
                'https://www.onemap.gov.sg/api/common/elastic/search',
                params={'searchVal': postcode, 'returnGeom': 'Y',
                        'getAddrDetails': 'Y', 'pageNum': 1},
                headers={'Authorization': token},
                timeout=20
            )
            response.raise_for_status()
            data = response.json()
        except (requests.RequestException, ValueError):
            raise gr.Error('OneMap postal-code search is unavailable. '
                           'Try again or enter exact coordinates manually.')
        error = str(data.get('error', ''))
        if error and 'token' in error.lower() and attempt == 0:
            ONEMAP_TOKEN, ONEMAP_EXPIRY = None, 0.0
            continue
        if error:
            raise gr.Error(f'OneMap search: {error}')
        matches = [item for item in data.get('results', [])
                   if str(item.get('POSTAL', '')) == postcode]
        if not matches:
            raise gr.Error('That postal code was not found. Check it '
                           'or enter exact playground coordinates manually.')
        return (float(matches[0]['LATITUDE']),
                float(matches[0]['LONGITUDE']))
    raise gr.Error('OneMap could not verify your location. '
                   'Enter exact coordinates manually.')

def validate_singapore_coordinates(lat, lon):
    lat, lon = float(lat), float(lon)
    if not (1.15 <= lat <= 1.48 and 103.58 <= lon <= 104.10):
        raise gr.Error('These coordinates are outside Singapore. '
                       'Check whether latitude and longitude are swapped.')
    return lat, lon

def gps_from_photo(photo):
    """Use original GPS metadata if a phone photo includes it."""
    try:
        gps = photo.getexif().get_ifd(ExifTags.IFD.GPSInfo)
        if not gps or 2 not in gps or 4 not in gps:
            return None
        def decimal(degrees_minutes_seconds):
            d, m, s = [float(x) for x in degrees_minutes_seconds]
            return d + m / 60 + s / 3600
        lat = decimal(gps[2]) * (-1 if gps.get(1) == 'S' else 1)
        lon = decimal(gps[4]) * (-1 if gps.get(3) == 'W' else 1)
        return validate_singapore_coordinates(lat, lon)
    except (TypeError, ValueError, KeyError, AttributeError, ZeroDivisionError, gr.Error):
        return None

def resolve_playground_location(photo, postal_code, exact_coordinates='',
                                lat=None, lon=None):
    """Priority: pasted playground point, manual pair, photo GPS, HDB postcode."""
    text = str(exact_coordinates or '').strip()
    if text:
        match = re.fullmatch(
            r'\s*([+-]?\d+(?:\.\d+)?)\s*,\s*([+-]?\d+(?:\.\d+)?)\s*', text
        )
        if not match:
            raise gr.Error('Paste coordinates as latitude, longitude, '
                           'for example: 1.390123, 103.891234')
        return (*validate_singapore_coordinates(*match.groups()),
                'Exact playground point pasted from a map')
    if lat is not None or lon is not None:
        if lat is None or lon is None:
            raise gr.Error('Enter both latitude and longitude, or leave both blank.')
        return (*validate_singapore_coordinates(lat, lon),
                'Manually entered playground coordinates')
    photo_gps = gps_from_photo(photo)
    if photo_gps:
        return (*photo_gps, 'GPS metadata from original photograph')
    if str(postal_code or '').strip():
        coords = validate_singapore_coordinates(*postal_to_coordinates(postal_code))
        return (*coords, 'Approximate HDB block location from postal code')
    return None, None, 'Not mapped: add exact GPS or postal code'

def classify_photo(photo):
    image = ImageOps.exif_transpose(photo).convert('RGB')
    original_size = image.size
    image.thumbnail((1200, 1200))
    inputs = processor(images=image, return_tensors='pt').to(device)
    with torch.no_grad():
        outputs = model(**inputs)
    mask = processor.post_process_semantic_segmentation(
        outputs, target_sizes=[(image.height, image.width)]
    )[0].cpu().numpy()
    return image, original_size, mask

def make_full_figure(image, mask):
    present, counts = np.unique(mask, return_counts=True)
    found = sorted(zip(present, counts), key=lambda p: p[1], reverse=True)
    handles = [
        Patch(color=PALETTE[int(c)] / 255,
              label=f'{CLASS_NAMES[int(c)].title()}: {100 * n / mask.size:.1f}%')
        for c, n in found
    ]
    legend_rows = int(np.ceil(len(handles) / 4))
    fig = plt.figure(figsize=(10, 7 + 0.4 * legend_rows), facecolor='white')
    grid = fig.add_gridspec(2, 1, left=.04, right=.96, top=.96,
                           bottom=max(.14, .055 * legend_rows), hspace=.13)
    top = fig.add_subplot(grid[0])
    bottom = fig.add_subplot(grid[1])
    top.imshow(image)
    top.set_title('Original Playground Photograph', fontsize=12)
    bottom.imshow(PALETTE[mask])
    bottom.set_title('Full SegFormer Segmentation', fontsize=12)
    for axis in [top, bottom]:
        axis.axis('off')
    fig.legend(handles=handles, loc='lower center', bbox_to_anchor=(.5, .01),
               ncol=4, fontsize=8, frameon=False)
    buffer = io.BytesIO()
    fig.savefig(buffer, format='png', dpi=130, bbox_inches='tight')
    plt.close(fig)
    buffer.seek(0)
    return Image.open(buffer).convert('RGB')

def make_focus_mask(mask):
    result = np.zeros(mask.shape, dtype=np.uint8)
    result[np.isin(mask, TREE_IDS)] = 1
    result[np.isin(mask, LOW_VEG_IDS)] = 2
    result[np.isin(mask, SKY_IDS)] = 3
    result[np.isin(mask, BUILDING_IDS)] = 4
    return Image.fromarray(FOCUS_PALETTE[result])

def results_table(rows):
    df = pd.DataFrame(rows, columns=COLUMNS).copy()
    if df.empty:
        return df
    # Exploratory sample-relative rule, NOT a validated shade threshold.
    if len(df) >= 5:
        low_tree = df['tree_pct'].quantile(.25)
        high_sky = df['sky_pct'].quantile(.75)
        flagged = (df['tree_pct'] <= low_tree) & (df['sky_pct'] >= high_sky)
        df['screening_note'] = np.where(
            flagged, 'Relative photo-review candidate', 'Not flagged by relative rule'
        )
    else:
        df['screening_note'] = 'Need at least 5 photos for relative screening'
    return df

def build_map(df):
    valid = df.copy()
    for field in ['latitude', 'longitude']:
        valid[field] = pd.to_numeric(valid[field], errors='coerce')
    valid = valid.dropna(subset=['latitude', 'longitude'])
    # Singapore-only study: ignore old or imported out-of-country pins.
    valid = valid[valid['latitude'].between(1.15, 1.48)
                  & valid['longitude'].between(103.58, 104.10)]
    if valid.empty:
        return None
    m = folium.Map(location=[valid['latitude'].mean(), valid['longitude'].mean()],
                   zoom_start=16 if len(valid) == 1 else 14,
                   tiles='OpenStreetMap')
    for _, item in valid.iterrows():
        candidate = str(item['screening_note']).startswith('Relative')
        content = (f'<b>{html.escape(str(item["playground_id"]))}</b><br>'
                   f'{html.escape(str(item["location"]))}<br>'
                   f'Tree: {item["tree_pct"]}%<br>'
                   f'Vegetation: {item["vegetation_pct"]}%<br>'
                   f'Sky: {item["sky_pct"]}%<br>'
                   f'Buildings: {item["buildings_pct"]}%<br>'
                   f'{html.escape(str(item["screening_note"]))}')
        folium.CircleMarker(
            location=[item['latitude'], item['longitude']],
            radius=7, fill=True,
            color='#e39826' if candidate else '#2675b5',
            popup=folium.Popup(content, max_width=260)
        ).add_to(m)
    if len(valid) >= 2:
        m.fit_bounds(valid[['latitude', 'longitude']].values.tolist(),
                     padding=(30, 30))
    return m

def create_map(df):
    m = build_map(df)
    if m is None:
        return '<div style="padding:16px">No mapped playgrounds yet. Paste exact GPS or add a Singapore postal code.</div>'
    return m._repr_html_()

def export_map_html(df):
    m = build_map(df)
    if m is None:
        return '<html><body><p>No locations were available for mapping.</p></body></html>'
    return m.get_root().render()

