def get_manifest(file_path=None, zip_archive=None):
    """External CSV takes priority; otherwise read locations.csv inside ZIP."""
    try:
        if file_path:
            manifest = pd.read_csv(file_path, dtype=str).fillna('')
        else:
            embedded = [item for item in (zip_archive.infolist() if zip_archive else [])
                        if item.filename.replace('\\', '/').split('/')[-1].lower()
                        == 'locations.csv' and item.file_size <= 2_000_000]
            if not embedded:
                return {}
            with zip_archive.open(embedded[0]) as file:
                manifest = pd.read_csv(io.BytesIO(file.read()), dtype=str).fillna('')
    except (OSError, ValueError, pd.errors.ParserError, UnicodeError):
        raise gr.Error('Could not read locations.csv. Download the template '
                       'and save it as a normal CSV file.')
    manifest.columns = [str(x).strip().lower() for x in manifest.columns]
    if 'filename' not in manifest.columns:
        raise gr.Error('Your locations.csv must have a filename column.')
    mapping = {}
    for row in manifest.to_dict(orient='records'):
        filename = str(row.get('filename', '')).strip().replace('\\', '/')
        if not filename:
            continue
        key = filename.lower()
        if key in mapping:
            raise gr.Error(f'Duplicate filename in locations.csv: {filename}')
        mapping[key] = row
    return mapping

def optional_float(value):
    value = str(value if value is not None else '').strip()
    if not value:
        return None
    try:
        return float(value)
    except ValueError:
        raise gr.Error(f'Invalid coordinate in locations.csv: {value}')

def analyse_zip(zip_path, manifest_path, records,
                progress=gr.Progress()):
    """Process JPG, PNG and WebP photos sequentially; never extract ZIP paths."""
    if not zip_path:
        raise gr.Error('Please upload a ZIP containing playground photos.')
    zip_path = Path(zip_path)
    if zip_path.stat().st_size > 250 * 1024 * 1024:
        raise gr.Error('The ZIP is too large. Please keep it under 250 MB.')

    rows = [dict(x) for x in (records or [])]
    previews = []
    warnings = []
    count = 0
    mapped = 0
    seen_ids = set()
    result_zip_path = OUTPUT_DIR / f'playground_batch_{uuid.uuid4().hex[:8]}.zip'

    try:
        with zipfile.ZipFile(zip_path, 'r') as source_zip:
            manifest = get_manifest(manifest_path, source_zip)
            images = [info for info in source_zip.infolist()
                      if not info.is_dir()
                      and Path(info.filename).suffix.lower()
                      in {'.jpg', '.jpeg', '.png', '.webp'}
                      and '__MACOSX' not in info.filename
                      and not Path(info.filename).name.startswith('.')]

            if not images:
                raise gr.Error('No supported photos found. Use JPG, PNG or WebP.')
            if len(images) > 80:
                raise gr.Error('Please upload no more than 80 photos in one ZIP.')
            if sum(info.file_size for info in images) > 750 * 1024 * 1024:
                raise gr.Error('Uncompressed images are too large for Colab.')

            with zipfile.ZipFile(result_zip_path, 'w',
                                 compression=zipfile.ZIP_DEFLATED) as output_zip:
                for index, info in enumerate(images, start=1):
                    filename = info.filename.replace('\\', '/')
                    progress((index - 1) / len(images),
                             desc=f'Analysing {index}/{len(images)}: {filename}')
                    if info.file_size > 25 * 1024 * 1024:
                        warnings.append(f'{filename}: image exceeds 25 MB')
                        continue
                    try:
                        with source_zip.open(info) as file:
                            payload = file.read(25 * 1024 * 1024 + 1)
                        if len(payload) > 25 * 1024 * 1024:
                            raise ValueError('image exceeds 25 MB')
                        with Image.open(io.BytesIO(payload)) as opened:
                            opened.load()
                            photo = opened.copy()

                        meta = (manifest.get(filename.lower()) or
                                manifest.get(Path(filename).name.lower()) or {})
                        generated_id = re.sub(
                            r'[^a-zA-Z0-9_-]+', '_',
                            Path(filename).stem
                        )[:40]
                        playground_id = str(
                            meta.get('playground_id') or generated_id or f'P{index:03d}'
                        ).strip()
                        if playground_id in seen_ids:
                            original_id = playground_id
                            playground_id = f'{original_id}_photo{index:03d}'
                            warnings.append(
                                f'{filename}: repeated ID {original_id}; '
                                f'saved separately as {playground_id}'
                            )
                        seen_ids.add(playground_id)

                        full, focus, record, map_source = analyse_photo_to_record(
                            photo=photo,
                            playground_id=playground_id,
                            location=meta.get('location', ''),
                            postal_code=meta.get('postal_code', ''),
                            exact_coordinates=meta.get('coordinates', ''),
                            lat=optional_float(meta.get('latitude')),
                            lon=optional_float(meta.get('longitude')),
                            shelter=meta.get('shelter_visible') or 'Unclear',
                            source=meta.get('photo_source') or 'Online source not yet verified',
                            lenient_location=True
                        )

                        rows = [r for r in rows
                                if str(r.get('playground_id')) != playground_id]
                        rows.append(record)
                        count += 1
                        if record['latitude'] is not None:
                            mapped += 1

                        safe_id = re.sub(r'[^a-zA-Z0-9_-]+', '_', playground_id)[:50]
                        prefix = f'images/{index:03d}_{safe_id}'
                        for suffix, picture in [
                            ('full_segmentation', full),
                            ('focus_mask', focus)
                        ]:
                            image_bytes = io.BytesIO()
                            picture.save(image_bytes, format='PNG')
                            output_zip.writestr(f'{prefix}_{suffix}.png',
                                                image_bytes.getvalue())

                        if len(previews) < 8:
                            previews.append((full, f'{playground_id}: {map_source}'))

                    except (OSError, ValueError, KeyError, gr.Error,
                            Image.DecompressionBombError) as error:
                        warnings.append(f'{filename}: {str(error)[:200]}')
                        continue

                if count == 0:
                    raise gr.Error('No photos could be analysed. Check the '
                                   'ZIP images and optional locations.csv.')

                df = results_table(rows)
                output_zip.writestr('playground_results.csv',
                                    df.to_csv(index=False))
                output_zip.writestr('playground_map.html', export_map_html(df))
                output_zip.writestr('processing_notes.txt',
                    'AI results describe visible image pixels, not actual shade.\n'
                    'Postal-code pins mark buildings, not exact playground points.\n'
                    'For accurate locations, add exact coordinates in locations.csv.\n\n'
                    + ('\n'.join(warnings) if warnings else 'No files skipped.'))

    except zipfile.BadZipFile:
        raise gr.Error('That file is not a valid ZIP archive.')

    progress(1.0, desc='Finished')
    df = results_table(rows)
    summary = (f'### Analysed {count} photos\n'
               f'- **Mapped playgrounds in this ZIP:** {mapped}\n'
               f'- **Without a valid map location:** {count - mapped}\n'
               f'- **Skipped or warning entries:** {len(warnings)}\n\n'
               'Download the results ZIP for **all images, CSV and interactive map**. '
               'Only the first eight images are previewed below.')
    if warnings:
        summary += '\n\n**Review:** ' + '; '.join(warnings[:3])
    return (summary, previews, str(result_zip_path), df,
            create_map(df), save_csv(df), df.to_dict(orient='records'))

